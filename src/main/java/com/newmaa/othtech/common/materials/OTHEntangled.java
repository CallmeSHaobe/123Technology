package com.newmaa.othtech.common.materials;

import java.util.ArrayList;
import java.util.List;
import java.util.function.Supplier;

import net.minecraftforge.fluids.Fluid;
import net.minecraftforge.fluids.FluidRegistry;
import net.minecraftforge.fluids.FluidStack;

import com.newmaa.othtech.OTHTechnology;

import gregtech.api.enums.FluidState;
import gregtech.api.enums.GTValues;
import gregtech.api.enums.TierEU;
import gregtech.api.fluid.GTFluidFactory;
import gregtech.api.interfaces.fluid.IGTFluidBuilder;
import tectech.recipe.TecTechRecipeMaps;

public final class OTHEntangled {

    public static final int UNIT = 1000;
    public static final int DURATION = 40 * 20;
    public static final long EUT = TierEU.RECIPE_UXV;

    private static final List<OTHEntangled> ALL = new ArrayList<>();

    public static final OTHEntangled Void;
    public static final OTHEntangled Stars;
    public static final OTHEntangled SuperconductorUIV;
    public static final OTHEntangled SuperconductorUMV;

    static {
        Void = new OTHEntangled(
            "void",
            "Entangled Void Entropy Flow",
            0xA6D4DF,
            () -> BWLiquids.Void.getFluidOrGas(UNIT));
        Stars = new OTHEntangled(
            "stars",
            "Entangled Molten Stardust",
            0xDDE2BC,
            () -> BWLiquids.Stars.getFluidOrGas(UNIT));
        SuperconductorUIV = new OTHEntangled(
            "superconductoruiv",
            "Entangled Superconductor UIV Base",
            0x99CCFF,
            () -> FluidRegistry.getFluidStack("molten.superconductoruivbase", UNIT));
        SuperconductorUMV = new OTHEntangled(
            "superconductorumv",
            "Entangled Superconductor UMV Base",
            0xCC99FF,
            () -> FluidRegistry.getFluidStack("molten.superconductorumvbase", UNIT));

    }

    private final String id;
    private final String defaultName;
    private final short[] rgba;
    private final Supplier<FluidStack> source;
    private Fluid entangled;

    private OTHEntangled(String id, String defaultName, int rgb, Supplier<FluidStack> source) {
        this.id = id;
        this.defaultName = defaultName;
        this.rgba = new short[] { (short) (rgb >> 16 & 0xFF), (short) (rgb >> 8 & 0xFF), (short) (rgb & 0xFF), 0 };
        this.source = source;
        ALL.add(this);
    }

    public String getName() {
        return "entangled_oth_" + id;
    }

    public Fluid getEntangledFluid() {
        return entangled;
    }

    public boolean isAvailable() {
        return entangled != null;
    }

    public FluidStack getEntangled(int amount) {
        if (entangled == null) {
            OTHTechnology.LOG.error("Entangled fluid {} is not registered yet", getName());
            return null;
        }
        return new FluidStack(entangled, amount);
    }

    public static List<OTHEntangled> getAll() {
        return ALL;
    }

    public static boolean isEntangled(Fluid fluid) {
        if (fluid == null) return false;
        for (OTHEntangled type : ALL) {
            if (type.entangled == fluid) return true;
        }
        return false;
    }

    public static void registerFluids() {
        for (OTHEntangled type : ALL) {
            IGTFluidBuilder builder = GTFluidFactory.builder(type.getName())
                .withColorRGBA(type.rgba)
                .withDefaultLocalName(type.defaultName)
                .withStateAndTemperature(FluidState.GAS, 0);

            final Fluid inherited = resolveSource(type);
            if (inherited != null) {
                builder = builder.withIconsFrom(inherited);
            } else {
                builder = builder.withTextureName("autogenerated");
            }

            type.entangled = builder.buildAndRegister()
                .asFluid();
        }
        OTHTechnology.LOG.info("Registered {} entangled fluids for 123 Technology", ALL.size());
    }

    private static Fluid resolveSource(OTHEntangled type) {
        try {
            final FluidStack stack = type.source.get();
            return stack == null ? null : stack.getFluid();
        } catch (RuntimeException e) {
            return null;
        }
    }

    public static void registerRecipes() {
        for (OTHEntangled type : ALL) {
            final FluidStack sourceStack = type.source.get();
            if (sourceStack == null || sourceStack.getFluid() == null) {
                OTHTechnology.LOG
                    .warn("Source fluid for {} is missing, condensate generator recipe skipped", type.getName());
                continue;
            }
            if (!type.isAvailable()) {
                OTHTechnology.LOG
                    .warn("Entangled fluid {} is missing, condensate generator recipe skipped", type.getName());
                continue;
            }

            GTValues.RA.stdBuilder()
                .fluidInputs(new FluidStack(sourceStack.getFluid(), UNIT))
                .fluidOutputs(new FluidStack(type.entangled, UNIT))
                .duration(DURATION)
                .eut(EUT)
                .addTo(TecTechRecipeMaps.condensateGeneratorRecipes);
        }
    }
}
